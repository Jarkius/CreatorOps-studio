import {
  ApiError,
  EXPORT_LIMITS,
  type ApiClient,
  type DraftScene,
  type SetDraftAssetsRequest,
  type UploadMime,
} from '@creatorops/contracts';

import { MetaAiError } from './runner.js';
import { META_AI_SITE, type HelperKind, type HelperSite } from './sites.js';

export const META_AI_GENERATOR = 'Meta AI';

const EXTENSION_FOR: Readonly<Record<UploadMime, string>> = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/webp': 'webp',
  'image/gif': 'gif',
  'video/mp4': 'mp4',
};

/** A plain file name: the scene and the time, ASCII only. */
export function generatedFileName(
  scene: DraftScene,
  mimeType: UploadMime,
  at: Date,
  prefix: string = META_AI_SITE.filePrefix,
): string {
  const stamp = at.toISOString().replace(/[-:]/g, '').slice(0, 15);
  return `${prefix}-${scene.replace('_', '-')}-${stamp}.${EXTENSION_FOR[mimeType]}`;
}

interface AttachedItem {
  readonly assetId: string;
  readonly role: 'cover' | 'media';
  readonly scene: DraftScene | null;
  readonly aiGenerated: boolean;
  readonly generator: string | null;
  /** Missing means an image (older callers). */
  readonly kind?: HelperKind;
}

/**
 * The new ordered attachment list: everything already attached stays (order, cover, labels), the
 * old file of this scene **of the same kind** (image or video) is replaced, so a scene can hold one
 * image and one video, and the new one goes last, marked as AI-generated by the site's label
 * (D-071 item 3, D-070 item 6). Throws when the draft would hold more than the limit.
 */
export function attachmentsWith(
  existing: readonly AttachedItem[],
  scene: DraftScene,
  assetId: string,
  made: { readonly generator: string; readonly kind: HelperKind } = {
    generator: META_AI_GENERATOR,
    kind: 'image',
  },
): SetDraftAssetsRequest {
  const kept = existing.filter(
    (item) => !(item.scene === scene && (item.kind ?? 'image') === made.kind),
  );
  if (kept.length + 1 > EXPORT_LIMITS.maxAssetsPerDraft) {
    throw new MetaAiError(
      'UPLOAD_FAILED',
      `A draft can hold ${EXPORT_LIMITS.maxAssetsPerDraft} files. Remove one in the dashboard first.`,
    );
  }
  return {
    assets: [
      ...kept.map((item) => ({
        assetId: item.assetId,
        role: item.role,
        scene: item.scene,
        aiGenerated: item.aiGenerated,
        generator: item.generator,
      })),
      { assetId, role: 'media', scene, aiGenerated: true, generator: made.generator },
    ],
  };
}

export interface AttachOptions {
  readonly api: ApiClient;
  readonly workspaceId: string;
  readonly draftId: string;
  readonly productId: string;
  readonly scene: DraftScene;
  readonly bytes: Uint8Array;
  readonly mimeType: UploadMime;
  readonly signal: AbortSignal;
  /** The site that made the file; Meta AI when left out. */
  readonly site?: HelperSite;
  readonly now?: () => Date;
  readonly fetchImpl?: typeof fetch;
}

/**
 * Saves a generated file through the existing upload path (intent, signed PUT, complete) and
 * attaches it to the scene. The file is on the server before the run ends, so closing the panel
 * afterwards loses nothing.
 */
export async function uploadAndAttach(options: AttachOptions): Promise<void> {
  const { api, workspaceId, draftId, scene, bytes, mimeType, signal } = options;
  const doFetch = options.fetchImpl ?? fetch;
  const site = options.site ?? META_AI_SITE;
  const kind: HelperKind = mimeType === 'video/mp4' ? 'video' : 'image';
  const fail = (message: string): never => {
    throw new MetaAiError('UPLOAD_FAILED', message);
  };
  try {
    const intent = await api.assets.createUploadIntent(workspaceId, {
      filename: generatedFileName(
        scene,
        mimeType,
        (options.now ?? (() => new Date()))(),
        site.filePrefix,
      ),
      mimeType,
      sizeBytes: bytes.byteLength,
      productId: options.productId,
    });
    if (signal.aborted) throw new MetaAiError('CANCELLED', 'Cancelled.');
    // No bearer token: the upload address carries its own signature.
    const put = await doFetch(api.resolveUrl(intent.uploadUrl), {
      method: 'PUT',
      headers: { 'content-type': intent.contentType },
      body: new Blob([bytes as BlobPart], { type: intent.contentType }),
      signal,
    });
    if (!put.ok) fail('The server did not accept the file. Please try again.');
    const asset = await api.assets.completeUpload(workspaceId, { intentId: intent.intentId });
    const current = await api.drafts.listAssets(workspaceId, draftId);
    await api.drafts.setAssets(
      workspaceId,
      draftId,
      attachmentsWith(
        current.items.map((item) => ({
          assetId: item.assetId,
          role: item.role,
          scene: item.scene,
          aiGenerated: item.aiGenerated,
          generator: item.generator,
          kind: item.asset.type === 'video' ? ('video' as const) : ('image' as const),
        })),
        scene,
        asset.id,
        { generator: site.generator, kind },
      ),
    );
  } catch (error) {
    if (error instanceof MetaAiError) throw error;
    if (signal.aborted) throw new MetaAiError('CANCELLED', 'Cancelled.');
    if (error instanceof ApiError) {
      throw new MetaAiError('UPLOAD_FAILED', error.message);
    }
    throw new MetaAiError('UPLOAD_FAILED', 'Could not save the file. Please try again.');
  }
}
